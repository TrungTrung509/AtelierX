import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {readGlb,writeGlb} from '../../../../tools/showcase-glb.mjs';

const root=process.cwd();
const rel=p=>path.relative(root,p).split(path.sep).join('/');
const file=p=>path.resolve(root,p);
const sha=b=>createHash('sha256').update(b).digest('hex');
const hashFile=p=>sha(fs.readFileSync(file(p)));
const reviewPath='orders/ATEL-41/v3/shape-review-handoff.json';
const independentReviewPath='orders/ATEL-41/v3/independent-shape-review.json';
const shapePath='orders/ATEL-41/v3/designer/shape-manifest-v3.json';
const provenancePath='orders/ATEL-41/v3/designer/provenance-v3.json';
const review=JSON.parse(fs.readFileSync(file(reviewPath),'utf8'));
const shape=JSON.parse(fs.readFileSync(file(shapePath),'utf8'));
const presetPath='orders/ATEL-41/material/pbr-preset-v1.json';
const preset=JSON.parse(fs.readFileSync(file(presetPath),'utf8'));
if(review.orderId!=='ATEL-41'||review.revision!=='v3'||review.decision!=='pass')throw Error('v3 shape-review is not pass');
if(shape.orderId!=='ATEL-41'||shape.revision!=='v3'||shape.garment?.sha256!==review.artifacts.find(x=>x.path===shape.garment.path)?.sha256)throw Error('Shape manifest and review disagree');
const flow=JSON.parse(fs.readFileSync(file('orders/ATEL-41/studio-flow.json'),'utf8'));
if(flow.shapeApproved!==true||!flow.events.some(e=>e.stage==='shape-review'&&e.revision==='v3'&&e.file===reviewPath))throw Error('studio-flow has not registered the v3 shape-review handoff');
const source=shape.garment.path;
const sourceSha=hashFile(source);
if(sourceSha!==shape.garment.sha256)throw Error('Source garment hash mismatch');
const doc=readGlb(file(source));
const inputBinSha=sha(doc.bin);
const appearance=preset.appearance;
if(!doc.g.materials?.length)throw Error('Expected existing material group');
for(const material of doc.g.materials){
  material.pbrMetallicRoughness||={};
  material.pbrMetallicRoughness.baseColorFactor=[...appearance.baseColorFactorLinear];
  material.pbrMetallicRoughness.roughnessFactor=appearance.roughnessFactor;
  material.pbrMetallicRoughness.metallicFactor=appearance.metallicFactor;
}
const out='orders/ATEL-41/v3/material/garment-surface-v3.glb';
fs.mkdirSync(path.dirname(file(out)),{recursive:true});
writeGlb(file(out),doc);
const after=readGlb(file(out));
const outputBinSha=sha(after.bin);
if(inputBinSha!==outputBinSha)throw Error('Geometry/UV BIN data changed');
const materialCheck=after.g.materials.every(m=>JSON.stringify(m.pbrMetallicRoughness.baseColorFactor)===JSON.stringify(appearance.baseColorFactorLinear)&&m.pbrMetallicRoughness.roughnessFactor===appearance.roughnessFactor&&m.pbrMetallicRoughness.metallicFactor===appearance.metallicFactor);
if(!materialCheck)throw Error('Applied PBR values mismatch');
const evidenceDir='quality/evidence/ATEL-41/v3/material';
fs.mkdirSync(file(evidenceDir),{recursive:true});
const beforeDir='quality/evidence/ATEL-41/v3/material/before';
const evidenceFiles=[beforeDir+'/browser-result.json',...['front','back','side','oblique'].map(v=>beforeDir+'/'+v+'.png'),evidenceDir+'/browser-result.json',...['front','back','side','oblique'].map(v=>evidenceDir+'/'+v+'.png')];
const manifest={orderId:'ATEL-41',revision:'v3',stage:'surface',geometryChanged:false,sourceGeometry:{path:source,sha256:sourceSha},geometryUvDataSha256:inputBinSha,artifacts:[out,presetPath,reviewPath,independentReviewPath,shapePath,provenancePath,...evidenceFiles].map(p=>({path:p,sha256:hashFile(p)})),material:{name:preset.materialName,simulatedMaterial:appearance.simulatedMaterial,baseColorHexSRGB:appearance.baseColorHexSRGB,baseColorFactorLinear:appearance.baseColorFactorLinear,roughnessFactor:appearance.roughnessFactor,metallicFactor:appearance.metallicFactor},evidence:{before:{browserResult:beforeDir+'/browser-result.json',front:beforeDir+'/front.png',back:beforeDir+'/back.png'},after:{browserResult:evidenceDir+'/browser-result.json',front:evidenceDir+'/front.png',back:evidenceDir+'/back.png',side:evidenceDir+'/side.png',oblique:evidenceDir+'/oblique.png'}},validation:{sourceGlbSha256:sourceSha,outputGlbSha256:hashFile(out),inputBinSha256:inputBinSha,outputBinSha256:outputBinSha,geometryAndUvBinaryDataUnchanged:inputBinSha===outputBinSha,allPbrMaterialsMatchPreset:materialCheck}};
const manifestPath='orders/ATEL-41/v3/material/surface-manifest-v3.json';
fs.writeFileSync(file(manifestPath),JSON.stringify(manifest,null,2)+'\n');
console.log(manifestPath);
